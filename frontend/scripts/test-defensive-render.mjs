/** Exercise real defensive reports through the production report dispatcher. */
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createServer } from "vite";
import React from "react";
import { JSDOM } from "jsdom";
import { aggregateRows, alignedTicks, referenceComparison, pressureReview, isPersonalUse, damageScale, displayDamagePoints, defensiveRecovery } from "../src/utils/defensiveUsage.js";

const fixture = JSON.parse(await readFile(new URL("../../tests/fixtures/defensive_usage_page.json", import.meta.url), "utf8"));
const mage = fixture.content.timeline.pulls[0].players.find((p) => p.name === "Chocolate");
const entries = fixture.content.timeline.pulls.map((pull) => ({ pull, player: pull.players.find((p) => p.id === mage.id) }));
const rows = aggregateRows(entries, 1296878, 1);
assert.equal(rows.length, 2);
assert.notEqual(rows[0].anchor, rows[1].anchor, "Alignment uses each pull's actual cast timestamp");
assert.equal(aggregateRows(entries, 1296878, 100).length, 0, "Missing occurrences are excluded, not assigned a synthetic timing");
assert.deepEqual(alignedTicks(-36.378, 90), [-30, -15, 0, 15, 30, 45, 60, 75, 90]);
assert.equal(isPersonalUse({ lane: { category: "external_or_self" }, event: { selfUse: false } }), false);
assert.equal(isPersonalUse({ lane: { category: "consumable" }, event: { selfUse: true } }), true);
const ref = { trackedSpellIds: [6262], samples: [
  { duration: 60, bossEvents: [{ spellId: 999, time: 20 }], events: [{ spellId: 6262, time: 19 }], url: "source" },
  { duration: 25, bossEvents: [{ spellId: 999, time: 20 }], events: [] },
  { duration: 60, bossEvents: [], events: [] },
] };
const synthetic = [{ pull: { duration: 60, bossLanes: [{ spellId: 999, events: [{ time: 35 }] }] },
  player: { lanes: [{ spellId: 6262, category: "consumable", events: [{ time: 34, selfUse: true }] }] } }];
const comparison = referenceComparison(synthetic, ref, 999, 1)[0];
assert.equal(comparison.referenceTotal, 1, "Only samples with the actual mechanic and complete window enter denominator");
assert.equal(comparison.referenceUses, 1);
assert.equal(comparison.ownUses, 1);
assert.equal(comparison.medianOffset, -1);
const reviewPlayer = { lanes: [{ category: "personal", events: [{ time: 10, end: 20 }] }],
  pressure: [{ time: 12, damage: 1000, healAbsorbs: 0 }, { time: 22, damage: 100, healAbsorbs: 0 }] };
assert.deepEqual(pressureReview(reviewPlayer, {}), [reviewPlayer.pressure[1]]);
const ordinaryDamage = Array.from({ length: 30 }, (_, i) => ({ time: i * 2, damage: 100, absorbed: 50, mitigated: 50 }));
const spikyDamage = [...ordinaryDamage, { time: 60, damage: 100, absorbed: 100, mitigated: 999800 }];
assert.deepEqual(damageScale(spikyDamage), { maximum: 250, peak: 1000000, clipped: 1 });
assert.deepEqual(damageScale(spikyDamage, true), { maximum: 1000000, peak: 1000000, clipped: 0 });
assert.deepEqual(damageScale([]), { maximum: 1, peak: 0, clipped: 0 });
assert.equal(damageScale(spikyDamage.slice(-2)).clipped, 0, "Sparse samples retain full range");
const mitigationPoint = { damage: 100, absorbed: 50, mitigated: 9000, cooldownMitigated: 30, cooldownAbsorbed: 20 };
assert.equal(displayDamagePoints([mitigationPoint])[0].mitigated, 30, "Default excludes baseline mitigation");
assert.equal(displayDamagePoints([mitigationPoint], true)[0].mitigated, 9000);
assert.equal(displayDamagePoints([{ ...mitigationPoint, cooldownMitigated: undefined }])[0].mitigated, 0, "Missing estimates never fall back to baseline mitigation");

const recoveryCast = { event: { time: 10, end: 20, ready: 90 }, player: { deaths: [] }, pull: { duration: 100 } };
assert.deepEqual(defensiveRecovery(recoveryCast), { start: 20, end: 90, marker: true });
assert.deepEqual(defensiveRecovery({ ...recoveryCast, player: { deaths: [{ time: 70 }] } }), { start: 20, end: 70, marker: false });
assert.deepEqual(defensiveRecovery({ ...recoveryCast, pull: { duration: 60 } }), { start: 20, end: 60, marker: false });
assert.equal(defensiveRecovery({ ...recoveryCast, event: { ...recoveryCast.event, ready: null } }), null);

